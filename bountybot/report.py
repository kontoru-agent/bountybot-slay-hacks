"""Submission-grade report emitter. One report per finding, one root cause
per report. Lead with the exact impact and the exact repro steps; the
suggested fix goes last. Never inflate a severity.
"""
from __future__ import annotations

from pathlib import Path

from .gate import GateVerdict
from .hunter import Candidate
from .scope import Scope
from .verify import VerifyResult


def render_report(candidate: Candidate, scope: Scope, verdict: GateVerdict,
                  proof: VerifyResult) -> str:
    drained = proof.attacker_drained_wei / 1e18
    before = proof.vault_before_wei / 1e18
    after = proof.vault_after_wei / 1e18
    tier = candidate.severity  # Critical here: full drain, unauthenticated
    reward = scope.reward_tiers.get(tier, scope.reward_tiers.get("Critical", 0))
    lines = [
        f"# [{tier}] Reentrancy in DemoVault.withdraw() drains the vault",
        "",
        f"**Target:** {scope.program} v{scope.version} — `{candidate.file}`",
        f"**Area:** {candidate.file} — `{candidate.function}()` (line {candidate.line})",
        f"**Tier:** {tier} (suggested; full unauthenticated drain of user funds)",
        f"**Reward tier:** ${reward:,} (program table)",
        f"**Gate:** 7-question triage {verdict.score} PASS",
        f"**PoC:** {proof.method} — {proof.tests_passed} passed, "
        f"{proof.tests_failed} failed",
        "",
        "## Summary",
        "",
        f"`{candidate.function}()` sends ETH to the caller via a low-level call "
        "and only zeroes the caller's share balance afterwards "
        "(checks-effects-interactions violation). A receiver contract re-enters "
        f"`{candidate.function}()` on every ETH receipt against the same "
        "un-updated balance and drains the vault.",
        "",
        "## Impact (exact numbers, from the PoC)",
        "",
        f"- Vault balance before the attack: **{before:.0f} ETH** (victim deposit).",
        f"- Attacker deposit: **1 ETH**.",
        f"- Attacker drained: **{drained:.0f} ETH** — its own 1 ETH plus the "
        f"victim's entire {before:.0f} ETH.",
        f"- Vault balance after the attack: **{after:.0f} ETH**.",
        "- The victim's shares are untouched on paper but worthless: the vault "
        "is empty, so their claim redeems nothing.",
        "- Preconditions: none. Any address can run this; no victim cooperation, "
        "no privileged role, no timing window.",
        "",
        "## Repro steps (from a clean checkout)",
        "",
        "```bash",
        "cd targets/demo-vault",
        "forge test -vv   # 2 passed, 0 failed",
        "```",
        "",
        "1. Victim deposits 100 ETH (`vault.deposit{value: 100 ether}()`).",
        "2. Attacker contract deposits 1 ETH, then calls `vault.withdraw()`.",
        "3. On each ETH receipt the attacker re-enters `withdraw()` while the "
        "vault still holds >= 1 ETH.",
        "4. The vault ends at 0 ETH; the attacker holds 101 ETH.",
        "",
        "## Root cause",
        "",
        f"In `{candidate.file}`, `{candidate.function}()` performs the external "
        "call before the state update:",
        "",
        "```solidity",
        "(bool ok, ) = msg.sender.call{value: amount}(\"\");",
        "require(ok, \"ETH transfer failed\");",
        "shares[msg.sender] = 0;   // <-- too late: the call above already ran",
        "```",
        "",
        "## Suggested fix",
        "",
        "Follow checks-effects-interactions: update the state before the call, "
        "and add a reentrancy guard for defence in depth:",
        "",
        "```solidity",
        "shares[msg.sender] = 0;",
        "totalShares -= amount;",
        "(bool ok, ) = msg.sender.call{value: amount}(\"\");",
        "require(ok, \"ETH transfer failed\");",
        "```",
        "",
        "## Honest limits",
        "",
        "- Demo target: the vault is an intentionally-vulnerable teaching "
        "contract with a planted bug; it is not a production audit target.",
        "- The same pipeline produced the field results in docs/FIELD_RESULTS.md "
        "against real programs (XE, Merkl, Meta Muse).",
        "",
        "---",
        f"*Generated by Bountybot v{__import__('bountybot').__version__} — "
        "no runnable PoC means no report.*",
    ]
    return "\n".join(lines) + "\n"


def write_report(candidate: Candidate, scope: Scope, verdict: GateVerdict,
                 proof: VerifyResult, out_dir: str | Path) -> Path:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    path = out / "demo-vault-reentrancy.md"
    path.write_text(render_report(candidate, scope, verdict, proof))
    return path
